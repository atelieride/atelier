describe('lastPrompts (what the sessions were asked)', () => {
  const file = (body: string) => {
    const dir = mkdtempSync(join(tmpdir(), 'atl-prompts-'));
    const p = join(dir, 'conv.jsonl');
    writeFileSync(p, body);
    return p;
  };

  test('the person\'s typed prompts only, newest last, at most n', async () => {
    const body = user('First ask') + assistant('2026-10-01T10:01:00.000Z')
      + user([{ type: 'tool_result', tool_use_id: 'x', content: 'out' }])
      + user([{ type: 'text', text: 'array content is never taken' }])
      + user('meta note', { isMeta: true })
      + user('agent prompt', { isSidechain: true })
      + user('<task-notification><task-id>a1</task-id><status>completed</status></task-notification>')
      + user('<command-message>init</command-message>\n<command-name>/init</command-name>')
      + user('<local-command-stdout>done</local-command-stdout>')
      + user('<bash-input>ls</bash-input>')
      + user('Caveat: The messages below were generated by the user while running local commands.')
      + user('[Request interrupted by user]')
      + user('<system-reminder>ctx</system-reminder>Second ask\nwith two lines')
      + user('Third ask') + user('Fourth ask') + user('Fifth ask') + user('Sixth ask');
    const p = file(body);
    expect(await lastPrompts(p)).toEqual(['Second ask\nwith two lines', 'Third ask', 'Fourth ask', 'Fifth ask', 'Sixth ask']);
    expect(await lastPrompts(p, 2)).toEqual(['Fifth ask', 'Sixth ask']);
    expect(await lastPrompts(p, 50)).toEqual(['First ask', 'Second ask\nwith two lines', 'Third ask', 'Fourth ask', 'Fifth ask', 'Sixth ask']);
  });

  test('each prompt is cut to 1.5 KB and its token-like runs are redacted', async () => {
    const key = 'sk-ant-' + 'A1b2C3d4E5f6G7h8I9j0'.repeat(2);
    const [p] = await lastPrompts(file(user(`Use ${key} for the API\n` + 'x'.repeat(5000))));
    expect(p).not.toContain(key);
    expect(p).toContain('Use … for the API');
    expect(p!.length).toBeLessThanOrEqual(1536);
  });

  test('a big file: only its last 256 KB are read, and a line that starts exactly there is kept', async () => {
    const after = user('Last ask');
    const base = Buffer.byteLength(user('Kept: starts the tail', { pad: '' }) + after);
    // The tail is exactly these two lines: the first starts on the tail's first byte.
    const tailLine = user('Kept: starts the tail', { pad: 'p'.repeat(PROMPTS_TAIL_BYTES - base) });
    expect(Buffer.byteLength(tailLine + after)).toBe(PROMPTS_TAIL_BYTES);
    const p = file(user('Too old') + line({ type: 'assistant', pad: 'q'.repeat(10_000) }) + tailLine + after);
    expect(await lastPrompts(p)).toEqual(['Kept: starts the tail', 'Last ask']);
  });

  // POSIX: POSIX home fixtures through node:path.
  posixTest('a line cut by the tail is dropped; a missing file, a folder or a symlink give nothing', async () => {
    const p = file(user('Cut ' + 'y'.repeat(PROMPTS_TAIL_BYTES)) + user('After'));
    expect(await lastPrompts(p)).toEqual(['After']);
    const dir = mkdtempSync(join(tmpdir(), 'atl-prompts-'));
    symlinkSync(p, join(dir, 'link.jsonl'));
    expect(await lastPrompts(join(dir, 'link.jsonl'))).toEqual([]);
    expect(await lastPrompts(join(dir, 'missing.jsonl'))).toEqual([]);
    expect(await lastPrompts(dir)).toEqual([]);
  });
});

