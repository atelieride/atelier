const line = (o: object) => JSON.stringify(o) + '\n';
const user = (content: unknown, extra: object = {}) => line({ type: 'user', sessionId: 's', cwd: '/p', gitBranch: 'main', timestamp: '2026-10-01T10:00:00.000Z', message: { role: 'user', content }, ...extra });
const assistant = (ts: string, extra: object = {}) => line({ type: 'assistant', timestamp: ts, message: { role: 'assistant', content: [{ type: 'text', text: 'ok' }] }, ...extra });

describe('encodeProjectPath / projectFolders', () => {
  test('every character other than a letter or digit becomes a dash, like Claude Code', () => {
    expect(encodeProjectPath('/Users/me/repos/atelier')).toBe('-Users-me-repos-atelier');
    expect(encodeProjectPath('/Users/me/my.app_v2 x')).toBe('-Users-me-my-app-v2-x');
  });
  test('the root folder and the folders of its subfolders (decoding is ambiguous: prefixes of the encoded roots)', () => {
    const names = ['-p-app', '-p-app-api', '-p-app-web-src', '-p-apple', '-p-other', '-private-p-app'];
    expect(projectFolders(names, ['/p/app'])).toEqual(['-p-app', '-p-app-api', '-p-app-web-src']);
    // The window's root and its real path (e.g. /var → /private/var) both count.
    expect(projectFolders(names, ['/p/app', '/private/p/app'])).toEqual(['-p-app', '-p-app-api', '-p-app-web-src', '-private-p-app']);
  });
});

describe('promptText', () => {
  test('a plain prompt, as a string or text blocks, on one line', () => {
    expect(promptText({ type: 'user', message: { content: 'Fix the  login\nbug' } })).toBe('Fix the login bug');
    expect(promptText({ type: 'user', message: { content: [{ type: 'text', text: 'Add tests' }, { type: 'image', source: {} }] } })).toBe('Add tests');
  });
  test('skips meta, sidechain, tool results, commands, caveats, interruptions and bash mode', () => {
    const skipped = [
      { type: 'user', isMeta: true, message: { content: 'Caveat: hidden' } },
      { type: 'user', isSidechain: true, message: { content: 'agent prompt' } },
      { type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: 'x', content: 'out' }] } },
      { type: 'user', message: { content: '<command-message>init is analyzing</command-message>\n<command-name>/init</command-name>' } },
      { type: 'user', message: { content: '<local-command-stdout>done</local-command-stdout>' } },
      { type: 'user', message: { content: 'Caveat: The messages below were generated by the user while running local commands.' } },
      { type: 'user', message: { content: '[Request interrupted by user]' } },
      { type: 'user', message: { content: '<bash-input>ls</bash-input>' } },
      { type: 'user', message: { content: '   ' } },
      { type: 'assistant', message: { content: 'hello' } }
    ];
    for (const e of skipped) expect(promptText(e)).toBeNull();
  });
  test('drops system reminders and strips the remaining tags', () => {
    expect(promptText({ type: 'user', message: { content: '<system-reminder>ctx</system-reminder>Rename <b>the</b> button' } })).toBe('Rename the button');
  });
  test('long prompts are shortened', () => {
    expect(promptText({ type: 'user', message: { content: 'x'.repeat(1000) } })!.length).toBeLessThanOrEqual(300);
  });
});

describe('parseConversation', () => {
  test('cwd, branch, first prompt and the last activity', () => {
    const head = line({ type: 'summary', summary: 'Login bug fix', leafUuid: 'u' }) + user('<command-name>/clear</command-name>') + user('Fix the login bug') + assistant('2026-10-01T10:05:00.000Z');
    const tail = assistant('2026-10-02T08:00:00.000Z', { gitBranch: 'fix/login', uuid: 'u' }) + '{"type":"assistant","timestamp":"broken';
    const p = parseConversation(head, tail);
    expect(p).toEqual({ cwd: '/p', prompt: 'Fix the login bug', title: 'Login bug fix', branch: 'fix/login', at: Date.parse('2026-10-02T08:00:00.000Z') });
  });
  test('a custom title wins over the summary; the first prompt is the title otherwise', () => {
    const head = line({ type: 'summary', summary: 'Summary', leafUuid: 'u' }) + user('Do it', { uuid: 'u' });
    expect(parseConversation(head, '', 's').title).toBe('Summary');
    expect(parseConversation(head, line({ type: 'custom-title', customTitle: 'My title', sessionId: 's' }), 's').title).toBe('My title');
    expect(parseConversation(user('Do it'), '', 's').title).toBe('Do it');
  });
  test('Claude\'s picker order: agent name, custom title, AI title, summary, first prompt; the last entry of each wins', () => {
    const head = line({ type: 'summary', summary: 'Summary', leafUuid: 'u' }) + user('Do it', { uuid: 'u' });
    const ai = (t: string, sessionId = 's') => line({ type: 'ai-title', aiTitle: t, sessionId });
    expect(parseConversation(head, ai('First AI') + ai('Fix the login flow'), 's').title).toBe('Fix the login flow');
    expect(parseConversation(head, ai('Fix the login flow') + line({ type: 'custom-title', customTitle: 'My title', sessionId: 's' }), 's').title).toBe('My title');
    expect(parseConversation(head, line({ type: 'custom-title', customTitle: 'My title', sessionId: 's' }) + line({ type: 'agent-name', agentName: 'Agent', sessionId: 's' }), 's').title).toBe('Agent');
    expect(parseConversation(head, ai('Theirs', 'other'), 's').title).toBe('Summary');
  });
  test('a tail starting mid-line ignores that partial line', () => {
    const tail = 'tamp":"2030-01-01T00:00:00.000Z"}\n' + assistant('2026-10-03T00:00:00.000Z');
    expect(parseConversation(user('x'), tail).at).toBe(Date.parse('2026-10-03T00:00:00.000Z'));
  });
  test('no real prompt (only sidechain, meta or commands): no prompt', () => {
    expect(parseConversation(user('agent', { isSidechain: true }) + user('meta', { isMeta: true }), '').prompt).toBeNull();
  });
  test('the cwd of the first non-sidechain entry', () => {
    expect(parseConversation(user('agent', { isSidechain: true, cwd: '/elsewhere' }) + user('Real', { cwd: '/p/api' }), '').cwd).toBe('/p/api');
  });
  test('summaries of other conversations (unknown leafUuid) are ignored; a summary of this one is used', () => {
    // Claude Code writes summaries of the project's other conversations at the top of a file, mapped by leafUuid.
    const others = line({ type: 'summary', summary: 'Other work A', leafUuid: 'x-1' }) + line({ type: 'summary', summary: 'Other work B', leafUuid: 'x-2' });
    const body = user('Fix the login bug', { uuid: 'u-1' }) + assistant('2026-10-01T10:05:00.000Z', { uuid: 'u-2', parentUuid: 'u-1' });
    expect(parseConversation(others + body, '', 's').title).toBe('Fix the login bug');
    const mine = line({ type: 'summary', summary: 'Login bug fix', leafUuid: 'u-2' });
    expect(parseConversation(others + mine + body, '', 's').title).toBe('Login bug fix');
    // The leaf may be in the tail of a big file.
    expect(parseConversation(others + mine + user('Fix the login bug', { uuid: 'u-1' }), assistant('2026-10-02T00:00:00.000Z', { uuid: 'u-2' }), 's').title).toBe('Login bug fix');
  });
  test('a custom title of another session id is ignored', () => {
    expect(parseConversation(user('Do it') + line({ type: 'custom-title', customTitle: 'Theirs', sessionId: 'other' }), '', 's').title).toBe('Do it');
    expect(parseConversation(user('Do it') + line({ type: 'custom-title', customTitle: 'Mine', sessionId: 's' }), '', 's').title).toBe('Mine');
  });
  test('the last activity of a big file comes from its tail only: none there, null (the caller uses the mtime)', () => {
    const head = user('Do it', { timestamp: '2026-10-01T10:00:00.000Z' }) + assistant('2026-10-01T11:00:00.000Z');
    expect(parseConversation(head, line({ type: 'file-history-snapshot', messageId: 'm' }), 's').at).toBeNull();
    expect(parseConversation(head, '', 's').at).toBe(Date.parse('2026-10-01T11:00:00.000Z'));
  });
});

