import { describe, expect, test } from 'vitest';
import { readOnlyCommand } from './readonly-command';

describe('readOnlyCommand', () => {
  test.each([
    `sed -n '1,40p' src/a.ts`,
    `sed -n 200,240p src/shared/session.ts; grep -n "x" src/b.ts | head -30`,
    `sed -ne '5p;10p' a.ts`,
    `sed -n '$p' a.ts`,
    `cat a.ts && wc -l b.ts`,
    `grep -rn "Unknown origin" src | grep -v test | head -30`,
    `git log --oneline -5 && git status --short`,
    `git -C /p --no-pager diff --stat -- src/a.ts`,
    `git branch`,
    `ls -la src 2>/dev/null`,
    `head -20 a.ts >/dev/null 2>&1`,
    `echo done >&2`,
    `find src -name '*.ts' -newer x`,
    `rg -n "foo|bar" src`,
    `cd /p && git diff`,
    `sort -u a | uniq`,
    `jq .version package.json`,
    `grep ">" a.ts`,
    `# look first\ncat a.ts`,
    `stat -f %m a.ts; du -sh src; tree -L 2 src`,
    `sed -n --expression=1p a.ts`,
    `sed -E -n 1p a.ts`,
    `cat a 2>&1`,
    `ls src/*.ts`,
    `git log --oneline -5`,
    `ls src/*.ts src/?.ts a[0-9]`,
    `uniq -c a.ts`,
    `git log -n 5`,
    `git show HEAD~1`,
    `git log --oneline HEAD~3..HEAD`,
    `sort ~/x a`,
    `grep -n "a\\.b" src`,
    `echo "say \\"hi\\""`,
    `grep -c x a.ts # count`,
    // Quoted or escaped operators are plain characters; a quoted `>&` target is still a descriptor in zsh.
    `grep -n \\> a.ts`,
    `grep -c '>' a.ts`,
    `echo a \\&\\& b \\| c \\; d`,
    `echo \\#x "#"y`,
    `echo "="ls \\=ls "~"`,
    `cat a >&"2"`,
    `cat a 2>&\\1`,
    `uniq a 2>&1`,
    `uniq 'a' 2>/dev/null`, // the quoting of an earlier word does not leak into the descriptor
  ])('read-only: %s', (cmd) => {
    expect(readOnlyCommand(cmd)).toBe(true);
  });

  test.each([
    `sed -i '' s/one/two/ src/*.ts`,
    `sed -n 's/a/b/w out' a.ts`,
    `sed -n '/error/p' a.ts`,
    `sed -n -f script.sed a.ts`,
    `sed 1,40p a.ts`,
    `cat > a.ts <<'EOF'\nx\nEOF`,
    `python3 - <<'EOF'\nprint(1)\nEOF`,
    `cat <<< hi`,
    `echo x > a.ts`,
    `echo x >> a.ts`,
    `echo x >| a.ts`,
    `cat a 2>&-`,
    `cat a | tee b`,
    `find . -name x -delete`,
    `find . -exec rm {} \\;`,
    `find . -fprint out`,
    `git checkout -- a.ts`,
    `git branch new-branch`,
    `git diff --output=x`,
    `git -c core.pager=less log`,
    `git log --ext-diff`,
    `sort -o out a`,
    `sort --output=out a`,
    `sort -uo out a`,
    `uniq a b`,
    `tree -o out src`,
    `rg --pre cat x`,
    `file -C -m magic`,
    `echo $(rm -rf x)`,
    'echo `touch x`',
    `echo "$(touch x)"`,
    `cat <(touch x)`,
    `grep x a &`,
    `(cd a && cat b)`,
    `{ cat a; }`,
    `FOO=1 cat a`,
    `GIT_EXTERNAL_DIFF=x git diff`,
    `/bin/cat a`,
    `npm test`,
    `npx vitest run 2>&1 | grep x`,
    `node x.js`,
    `xargs rm < list`,
    `awk '{print > "f"}' a`,
    `if true; then cat a; fi`,
    `cat 'a`,
    `cat "a`,
    `cat ${'a'.repeat(3000)}`,
    ``,
    `   `,
    `echo $'\\'' ; touch pwned ; echo \\'`,
    `echo "$\\\n(touch pwned)"`,
    `echo \\\ncat a`,
    'sort ${X:--opwned} a',
    'find . ${X:--delete}',
    'echo -opwned; sort $_ a',
    'printf -v X %s --output=p; git log $X',
    `sort {-o,pwned} a`,
    `find . {-delete,-print}`,
    `git log {--output=x,-1}`,
    `echo x | uniq - out`,
    `uniq -- -in out`,
    `git grep -Orm pattern`,
    `git grep --open=rm pattern`,
    `sort --outp=pwned a`,
    `sort --compress-program=./x -S 1K big`,
    `sort -T /tmp a`,
    `file --comp -m magic`,
    `tree -R -H . -L 2 src`,
    `tree --output=x src`,
    `test -v 'PATH[$(touch pwned)]'`,
    `printf -v 'a[$(touch pwned)]' x`,
    `[ 1 -eq 'x[$(touch pwned)]' ]`,
    `rg --hostname-bin=./script --hyperlink-format=default x`,
    `cat *.ts`,
    `ls *`,
    `cat [ab]x`,
    `cat ?x`,
    `echo {a,b}`,
    `echo }`,
    `echo "$HOME"`,
    `find . -execdir rm {} +`,
    `find . -ok rm {} \;`,
    `find . -okdir rm {} \;`,
    `find . -fprint0 out`,
    `find . -fprintf out x`,
    `find . -fls out`,
    `git log --open-files-in-pager=x`,
    `git grep -o x`,
    `git log --output-directory=x`,
    `git log --ext-diff`,
    `git -C`,
    `jq -i . a.json`,
    `jq --in-place . a.json`,
    `sed -n -e '/re/p' a.ts`,
    `sed -s -n 1p a.ts`,
    `cat a 3>file`,
    `cat a 10>file`,
    `cat a >&file`,
    `cat a <>file`,
    `cat a &>file`,
    `cat a &>>file`,
    `cat a |& cat`,
    `echo "a\\\nb"`,
    `printf -v X %s y`,
    `test -v 'a[0]'`,
    `[ -f a.ts ] && cat a.ts`,
    `printf %s x`,
    `test -f a.ts`,
    `printf -vPATH %s bin; ls`,
    `git grep -nOrm pattern`,
    `git log -nO./x`,
    `uniq a.ts -c`,
    `uniq a b -c`,
    `sort ''* a`,
    `sort -* a`,
    `find . -de*`,
    `ls ""?x`,
    `sort "-"* a`,
    `uniq src/*.txt`,
    `uniq -c logs/a*`,
    `uniq a?`,
    `sort ^x a`,
    `sort a^x ^y`,
    `sort ''~x a`,
    `sort ''#x a`,
    `sort -~x a`,
    `git -C x* status`,
    `git -C x? log`,
    // Every input redirection is refused: zsh reads `<->` and `<N-M>` as numeric-range globs, not redirections.
    `uniq <->>/dev/null`,
    `uniq a <->>/dev/null`,
    `uniq a<1-9>>/dev/null`,
    `uniq <->&1`,
    `cat < a.ts`,
    `cat 0< a.ts`,
    `cat <&0`,
    // An unquoted `#` that does not start a word is zsh EXTENDED_GLOB "zero or more of the previous character".
    `sort x#-ox a`,
    `git log x#--output=o`,
    `rg pat x#--pre=sh`,
    `ls a#*`,
    `cat "a"#b`,
    // Other zsh syntax the lexer must not read differently from zsh.
    `cat =ls`, // `=cmd` expands to the program's path
    `ls ~[x]`, // dynamic named directory: calls a shell function
    `cat a >&"\\1"`, // the backslash stays inside double quotes: `>&` to a file named `\1`
    `cat a; >/dev/null`, // a redirection without a command runs $NULLCMD
    `2>&1`,
    `echo x >! a.ts`,
    `echo x >>! a.ts`,
    `cat a &|`,
    `cat a &!`,
    `cat a ;& cat b`,
    `cat =(echo x)`,
    `cat a >(tee b)`,
    `cat a &>| b`,
    // A digit is a file descriptor only when the word is exactly that unquoted, unescaped digit; otherwise zsh keeps
    // it as an argument (`uniq a 1` writes the file `1`, `git branch 1` creates a branch).
    `uniq a ''1>/dev/null`,
    `uniq a \\1>/dev/null`,
    `uniq a "2">&1`,
    `git branch ''1>/dev/null`,
    `git branch 2"">&1`,
    // zsh equals expansion also applies after a quoted empty string (`''=ls` is `/bin/ls`).
    `cat ''=ls`,
    `cat ""=ls`
  ])('writer: %s', (cmd) => {
    expect(readOnlyCommand(cmd)).toBe(false);
  });
});
